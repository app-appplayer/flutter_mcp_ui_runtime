// Generates lib/src/utils/material_icons.g.dart from the Flutter SDK's
// `Icons` class, so every Material icon name resolves — the promise
// icon_resolver.dart makes ("names on fonts.google.com/icons and Flutter's
// `Icons`").
//
// Entries are written as codepoint literals rather than `Icons.<name>`
// references: the package supports Flutter >= 3.10, and a reference to an
// icon added later would not compile there.
//
// Usage (from the package root):
//   dart run tool/generate_material_icons.dart          # write
//   dart run tool/generate_material_icons.dart --check  # exit 1 if stale

import 'dart:io';

const _out = 'lib/src/utils/material_icons.g.dart';

/// One `static const IconData` declaration of `Icons`.
class MaterialIconEntry {
  MaterialIconEntry(this.identifier, this.codePoint, this.matchTextDirection,
      this.fontName);

  /// The Dart identifier (`ten_k`, `class_`, `home_outlined`).
  final String identifier;
  final int codePoint;
  final bool matchTextDirection;

  /// The font's own name from the doc comment (`10k`, `class`), base style
  /// only; null for style variants.
  final String? fontName;
}

/// Parses every `static const IconData` of the SDK's `icons.dart`.
List<MaterialIconEntry> parseFlutterIcons(String source) {
  // The doc comment carries the font's own name in its <i> tag; the class
  // suffix (`-sharp`, `-round`, `-outlined`) marks a style variant.
  final decl = RegExp(
    r'///\s*<i class="material-icons(-[a-z]+)? md-36">([^<]+)</i>[^\n]*\n'
    r'\s*static const IconData (\w+) = IconData\(\s*(0x[0-9a-fA-F]+),'
    r'([^;]*?)\);',
  );
  return [
    for (final m in decl.allMatches(source))
      MaterialIconEntry(
        m.group(3)!,
        int.parse(m.group(4)!),
        m.group(5)!.contains('matchTextDirection: true'),
        m.group(1) == null ? m.group(2) : null,
      ),
  ];
}

String _flutterIconsPath() {
  final root = Platform.environment['FLUTTER_ROOT'] ??
      File(Platform.resolvedExecutable).parent.parent.parent.parent.parent.path;
  return '$root/packages/flutter/lib/src/material/icons.dart';
}

String _render(List<MaterialIconEntry> entries, String sdkVersion) {
  final keys = <String, MaterialIconEntry>{};
  for (final e in entries) {
    keys[e.identifier] = e;
  }
  // The font's own name (`10k`, `class`) where it is not a Dart identifier.
  for (final e in entries) {
    final name = e.fontName;
    if (name != null && !keys.containsKey(name)) keys[name] = e;
  }
  final sorted = keys.keys.toList()..sort();
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_material_icons.dart from the')
    ..writeln('// Flutter $sdkVersion `Icons` class. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// Every Material icon by name: the `Icons` identifier')
    ..writeln('/// (`ten_k`, `class_`, `home_outlined`) and, where it differs,')
    ..writeln("/// the font's own name (`10k`, `class`).")
    ..writeln('const Map<String, IconData> materialIconsByName = {');
  for (final k in sorted) {
    final e = keys[k]!;
    final hex = '0x${e.codePoint.toRadixString(16)}';
    final mtd = e.matchTextDirection ? ', matchTextDirection: true' : '';
    b.writeln("  '$k': IconData($hex, fontFamily: 'MaterialIcons'$mtd),");
  }
  b.writeln('};');
  return b.toString();
}

String _sdkVersion() {
  final root = File(_flutterIconsPath()).parent.parent.parent.parent.parent.parent;
  final json = File('${root.path}/bin/cache/flutter.version.json');
  if (json.existsSync()) {
    final m = RegExp(r'"frameworkVersion"\s*:\s*"([^"]+)"')
        .firstMatch(json.readAsStringSync());
    if (m != null) return m.group(1)!;
  }
  return 'SDK';
}

void main(List<String> args) {
  final source = File(_flutterIconsPath()).readAsStringSync();
  final entries = parseFlutterIcons(source);
  if (entries.isEmpty) {
    stderr.writeln('No icons parsed from ${_flutterIconsPath()}');
    exit(2);
  }
  final text = _render(entries, _sdkVersion());
  final file = File(_out);
  if (args.contains('--check')) {
    final current = file.existsSync() ? file.readAsStringSync() : '';
    // The header names the SDK version; compare the table only.
    String body(String s) => s.substring(s.indexOf('import '));
    if (current.isEmpty || body(current) != body(text)) {
      stderr.writeln('$_out is stale: run tool/generate_material_icons.dart');
      exit(1);
    }
    stdout.writeln('$_out current (${entries.length} icons)');
    return;
  }
  file.writeAsStringSync(text);
  stdout.writeln('wrote $_out (${entries.length} icons)');
}
